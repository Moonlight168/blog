/**
 * 文档版本号：按「第几次保存」编。
 *
 *     第 1 次 → 1.0      第 2 次 → 1.01      第 3 次 → 1.02
 *
 * 为什么这样写：主号永远是 1（这份文档就一个东西），次号数的是保存次数——
 * 两位是为了列在历史里能对齐、好扫，也给以后留出插位。
 *
 * 只按**手动保存**计数：AI 改写本身不产生版本（改坏了有回撤栈兜着），
 * 点了「保存」才算数。这样历史里每一条都是"我当时认可并留下来的样子"。
 */
export function versionLabel(count: number): string {
  return count <= 1 ? "1.0" : `1.${String(count - 1).padStart(2, "0")}`;
}
